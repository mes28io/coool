// Downloads Pally (ITF Free Font License) from Fontshare into src/assets/fonts/pally/.
// The licence forbids redistributing the font files (including in public repositories),
// so they are fetched at install time and git-ignored. See src/assets/fonts/README.md.
// Never fails the install: if the download fails the UI falls back to Geist.
import { mkdir, writeFile, access } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const dir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../src/assets/fonts/pally");
const fontFile = path.join(dir, "Pally-Variable.woff2");
const cssFile = path.join(dir, "pally.css");
const API = "https://api.fontshare.com/v2/css?f[]=pally@1&display=swap"; // pally@1 = the variable font

const exists = (p) => access(p).then(() => true, () => false);

try {
  if ((await exists(fontFile)) && (await exists(cssFile)) && !process.argv.includes("--force")) {
    console.log("fetch-fonts: Pally already present");
    process.exit(0);
  }
  const css = await (await fetch(API)).text();
  const m = css.match(/url\('?(?:https:)?(\/\/[^')]+\.woff2)'?\)/);
  if (!m) throw new Error("no woff2 url in Fontshare CSS");
  const res = await fetch("https:" + m[1]);
  if (!res.ok) throw new Error(`font download ${res.status}`);
  const buf = Buffer.from(await res.arrayBuffer());
  if (buf.subarray(0, 4).toString() !== "wOF2") throw new Error("downloaded file is not woff2");
  await mkdir(dir, { recursive: true });
  await writeFile(fontFile, buf);
  await writeFile(
    cssFile,
    `/* generated by scripts/fetch-fonts.mjs, do not edit or commit */
@font-face {
  font-family: "Pally";
  src: url("./Pally-Variable.woff2") format("woff2");
  font-weight: 400 700;
  font-style: normal;
  font-display: block;
}
`,
  );
  console.log("fetch-fonts: Pally installed (" + buf.length + " bytes)");
} catch (e) {
  console.warn("fetch-fonts: could not fetch Pally (" + e.message + "); the UI will use Geist.");
}
